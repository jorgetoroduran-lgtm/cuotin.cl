const createEmptyPayments = (paidMonths: MonthKey[] = [], amount = 5000): Record<MonthKey, PaymentRecord> => {
  const months: MonthKey[] = ['mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'];
  const res = {} as Record<MonthKey, PaymentRecord>;

  const dateMap: Record<MonthKey, string> = {
    mar: '2026-03-05',
    abr: '2026-04-06',
    may: '2026-05-04',
    jun: '2026-06-05',
    jul: '2026-07-07',
    ago: '2026-08-05',
    sep: '2026-09-04',
    oct: '2026-10-06',
    nov: '2026-11-05',
    dic: '2026-12-04',
  };

  months.forEach((m) => {
    const isPaid = paidMonths.includes(m);
    res[m] = {
      month: m,
      isPaid,
      amount,
      paidAt: isPaid ? dateMap[m] : undefined,
      paymentMethod: isPaid ? 'Transferencia' : undefined,
      receiptNumber: isPaid ? `TRF-${Math.floor(100000 + Math.random() * 900000)}` : undefined,
      registeredBy: isPaid ? 'Carolina Herrera (Tesorera)' : undefined,
      notes: isPaid ? 'Comprobante recibido por WhatsApp' : undefined,
    };
  });

  return res;
};

